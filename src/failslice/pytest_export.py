"""Generate a self-contained pytest bundle from a verified run directory (ADR 0009).

Layout of a bundle directory::

    test_<name>.py            the test (polarity is one constant at the top)
    query.sql                 the predicate query; edit it after fixing your pipeline
    reproducer.json           predicate form and parameters, schemas, FKs, fixture hashes
    fixtures/tables/<table>.parquet  the reduced tables
    fixtures/orphans.parquet         input orphans that are allowed to dangle
    _failslice_portable.py    byte-identical copy of failslice/portable.py

The bundle needs only ``pytest`` and ``duckdb``. It never reads the original inputs and
contains no absolute paths, timestamps or run ids, so the same run gives the same files.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import secrets
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import duckdb
import yaml

from failslice import __version__, portable
from failslice.config import ExpectPredicate, RaisesPredicate, SqlPredicate, literal_path
from failslice.predicate import check_for, normalize_expected
from failslice.runspec import RunSpec, restoring_exprs

__all__ = ["ExportError", "PytestExport", "build_bundle"]

Polarity = Literal["fails", "passes"]

_NAME = re.compile(r"^[a-z_][a-z0-9_]*$")
PORTABLE_FILE = "_failslice_portable.py"


class ExportError(RuntimeError):
    """The bundle cannot be generated (invalid name, existing destination, a value the
    expectation codec cannot represent exactly, or a failed self-check)."""


@dataclass(frozen=True)
class PytestExport:
    """A generated bundle."""

    directory: Path
    test_file: Path
    expect: Polarity
    files: tuple[Path, ...]


_TEST_TEMPLATE = '''\
"""Regression test generated by FailSlice {version} (https://github.com/sdmhdn/failslice).

It rebuilds the reduced tables from ./fixtures, checks the fixture hashes, the schemas and
referential integrity (no dangling references except recorded input orphans), then runs
./query.sql and classifies the result exactly like FailSlice does
(./_failslice_portable.py).

EXPECT = "fails": the test passes while the bug is reproduced (predicate TRUE).
EXPECT = "passes": the test passes once the bug is gone (predicate FALSE).
Edit query.sql when your pipeline's SQL changes; the data in ./fixtures is a snapshot.
"""

import hashlib
import importlib.util
import sys
from pathlib import Path

BUNDLE = Path(__file__).resolve().parent
EXPECT = "{expect}"


def _portable():
    """Load this bundle's own copy of the FailSlice semantics under a unique name."""
    path = BUNDLE / "{portable_file}"
    name = "_failslice_portable_" + hashlib.sha256(str(BUNDLE).encode()).hexdigest()[:16]
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def test_{name}():
    result = _portable().run_bundle(BUNDLE)
    assert not result.problems, result.problems
    assert not result.violations, f"new dangling references: {{result.violations}}"
    wanted = "TRUE" if EXPECT == "fails" else "FALSE"
    outcome = result.outcome
    assert outcome is not None
    assert outcome.kind == wanted, f"predicate is {{outcome.kind}}: {{outcome.detail}}"
'''


def _check_name(name: str) -> None:
    if not _NAME.fullmatch(name):
        raise ExportError(f"test name {name!r} must match [a-z_][a-z0-9_]*")


def _predicate_entry(
    spec: RunSpec, run_dir: Path, deadline: float | None = None
) -> dict[str, object]:
    pred = spec.predicate
    if isinstance(pred, SqlPredicate):
        return {"form": "sql"}
    if isinstance(pred, RaisesPredicate):
        return {
            "form": "raises",
            "match": pred.match,
            "flags": pred.compiled().flags,
            "error_class": pred.error_class,
        }
    assert isinstance(pred, ExpectPredicate)
    if spec.expected_file:
        raw = duckdb.connect(":memory:")
        try:
            path = spec.resolve(run_dir, spec.expected_file)
            con = portable.DeadlineConnection(raw, deadline)
            rows = [
                tuple(r)
                for r in con.fetchall(
                    "SELECT * FROM read_parquet(" + portable._lit(str(path)) + ")"
                )
            ]
        finally:
            raw.close()
    else:
        rows = normalize_expected(yaml.safe_load(spec.expected_yaml or "null"))
    check = check_for(pred, rows)
    try:
        encoded = portable.encode_rows(rows)
    except TypeError as exc:
        raise ExportError(f"the expectation cannot be stored exactly: {exc}") from exc
    if not portable.results_equal(portable.decode_rows(encoded), rows, ordered=True, tol=None):
        raise ExportError("the expectation does not survive encoding exactly")  # pragma: no cover
    return {
        "form": "expect",
        "expected": encoded,
        "scalar": check.scalar,
        "mode": check.mode,
        "ordered": check.ordered,
        "tolerance": check.tolerance,
    }


def build_bundle(
    run_dir: str | Path,
    dest: str | Path,
    *,
    name: str | None = None,
    expect: Polarity = "fails",
    deadline: float | None = None,
) -> PytestExport:
    """Write a pytest bundle for the run in ``run_dir`` to the new directory ``dest``.

    The bundle is staged next to ``dest`` and renamed into place only after it passed a
    self-check (``run_bundle`` must classify the predicate as TRUE); ``dest`` must not
    exist. The caller is responsible for having verified the run directory.

    ``name`` defaults to ``reproducer_<hash>``, where the hash covers the fixtures and the
    polarity: pytest's default import mode needs distinct test-module names when several
    bundles are collected together.
    """
    if name is not None:
        _check_name(name)
    if expect not in ("fails", "passes"):
        raise ExportError(f"expect must be 'fails' or 'passes', not {expect!r}")
    root = Path(run_dir).resolve()
    target = Path(dest).resolve()
    literal_path(target)
    if target.exists():
        raise ExportError(f"destination {target} already exists")
    spec = RunSpec.read(root)
    stage = target.with_name(f".{target.name}.tmp-{secrets.token_hex(4)}")
    stage.mkdir(parents=True)
    try:
        (stage / "fixtures" / "tables").mkdir(parents=True)
        tables = []
        fixtures: dict[str, str] = {}
        for tname, entry in spec.tables.items():
            rel = f"fixtures/tables/{tname}.parquet"
            if not (stage / rel).resolve().is_relative_to(stage.resolve()):  # pragma: no cover
                raise ExportError(f"invalid table name {tname!r}")  # RunSpec validates names
            shutil.copyfile(_regular(spec.resolve(root, entry.file)), stage / rel)
            fixtures[rel] = portable._sha256(stage / rel)
            tables.append(
                {
                    "name": tname,
                    "file": rel,
                    "select": restoring_exprs(entry.columns, entry.source_columns),
                    "columns": [list(c) for c in entry.source_columns],
                }
            )
            _check_deadline(deadline)
        shutil.copyfile(
            _regular(spec.resolve(root, spec.orphans_file)), stage / "fixtures/orphans.parquet"
        )
        fixtures["fixtures/orphans.parquet"] = portable._sha256(stage / "fixtures/orphans.parquet")
        fks = []
        for text in spec.foreign_keys:
            child, parent = (part.strip() for part in text.split("->"))
            fks.append([*child.split(".", 1), *parent.split(".", 1)])
        pred = spec.predicate
        query = pred.sql if isinstance(pred, SqlPredicate) else pred.query
        predicate_entry = _predicate_entry(spec, root, deadline)
        reproducer: dict[str, object] = {
            "format": portable.BUNDLE_FORMAT,
            "portable_version": portable.PORTABLE_VERSION,
            "failslice_version": spec.failslice_version,
            "duckdb_version": spec.duckdb_version,
            "threads": spec.settings.threads,
            "eval_timeout_s": spec.settings.eval_timeout_s,
            "tables": tables,
            "foreign_keys": fks,
            "orphans": "fixtures/orphans.parquet",
            "predicate": predicate_entry,
            "fixtures": fixtures,
        }
        if name is None:  # distinct per complete bundle contract, query and polarity
            digest = json.dumps([reproducer, query, expect], sort_keys=True).encode()
            name = "reproducer_" + hashlib.sha256(digest).hexdigest()[:12]
        reproducer["name"] = name
        (stage / "query.sql").write_text(query.rstrip("\n") + "\n", encoding="utf-8")
        (stage / "reproducer.json").write_text(
            json.dumps(reproducer, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        shutil.copyfile(portable.__file__, stage / PORTABLE_FILE)
        test_file = stage / f"test_{name}.py"
        test_file.write_text(
            _TEST_TEMPLATE.format(
                version=__version__,
                expect=expect,
                name=name,
                portable_file=PORTABLE_FILE,
            ),
            encoding="utf-8",
        )
        _check_deadline(deadline)
        try:
            result = portable.run_bundle(stage, deadline=deadline)
        except TimeoutError as exc:
            raise ExportError("deadline exceeded while self-checking the pytest bundle") from exc
        if result.problems or result.violations or result.outcome is None:
            raise ExportError(f"bundle self-check failed: {result.problems or result.violations}")
        if not result.outcome.is_true:
            raise ExportError(
                f"bundle self-check: the predicate is {result.outcome.kind.value} on the "
                f"bundle ({result.outcome.detail}); the run directory does not reproduce"
            )
        _check_deadline(deadline)
        os.rename(stage, target)
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    files = tuple(sorted(p for p in target.rglob("*") if p.is_file()))
    return PytestExport(target, test_file_name(target, name), expect, files)


def test_file_name(directory: Path, name: str) -> Path:
    """Path of a bundle's test module."""
    return directory / f"test_{name}.py"


def _regular(path: Path) -> Path:
    """Only regular files are copied (a FIFO or device in a tampered run would block)."""
    if not path.is_file():
        raise ExportError(f"{path} is missing or not a regular file")
    return path


def _check_deadline(deadline: float | None) -> None:
    if deadline is not None and time.monotonic() > deadline:
        raise ExportError("deadline exceeded while generating the pytest bundle")
